def with_row_b(spec, stem, stems=_PANEL_B, full_width=False):
    """Replace row b's four images with one composed panel spanning the same width,
    or with full_width the width of panel a (the whole figure, 2026-10-24: the
    panel's bubbles grew into it).

    Its bottom stays where row b's was; a taller panel lifts everything above it
    and grows the page by the difference, as with_taller_panel does.
    """
    old = [t for t in spec["panels"] if t[0] in stems]
    x0 = min(t[1] for t in old)
    y0 = min(t[2] for t in old)
    w = max(t[1] + t[3] for t in old) - x0
    if full_width:
        a = next(t for t in spec["panels"] if t[0] == spec["boxes"][0])
        x0, w = a[1], a[3]
    top = max(_top(t) for t in old)
    dy = round(y0 + w / _aspect(stem) - top, 1)
    panels = [(st, x, y + dy, pw, L) if y >= top - 1e-6 else (st, x, y, pw, L)
              for st, x, y, pw, L in spec["panels"] if st not in stems]
    return {**spec, "size": (spec["size"][0], spec["size"][1] + dy),
            "panels": panels + [(stem, x0, y0, w, "b")]}


