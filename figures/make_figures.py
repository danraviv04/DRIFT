def with_b_beside_a(spec, a_width=None, gap_ab=24, gap_rz=6, gap_v=10, row_gap=22):
    """Move the b block (wt, wt_helix_zoom, mutant, mutant_helix_zoom) beside a.

    a_width None solves for a and b of equal height. Otherwise a gets that width
    and b fills the rest of the row, centred on a's height.
    """
    at = {p[0]: p for p in spec["panels"]}
    a_stem = spec["boxes"][0]   # panel a, whichever artwork the figure uses
    b_stems = ("wt", "wt_helix_zoom", "mutant", "mutant_helix_zoom")
    x0, avail = at[a_stem][1], at[a_stem][3]
    pad = spec.get("box_pad", dict.fromkeys("ltrb", 8))
    below = [p for p in spec["panels"] if p[0] != a_stem and p[0] not in b_stems]
    top2 = max(_top(p) for p in below)
    ar_a, ar_r, ar_z = _aspect(a_stem), _aspect("wt"), _aspect("wt_helix_zoom")
    k = (ar_r + ar_z) / 2
    if a_width is None:
        # wa + gap_ab + (ar_r + ar_z) * hp + gap_rz = avail, with 2 hp + gap_v = wa / ar_a
        a_width = (avail - gap_ab - gap_rz + k * gap_v) / (1 + k / ar_a)
    ha = a_width / ar_a
    hp = (avail - a_width - gap_ab - gap_rz) / (ar_r + ar_z)
    hb = 2 * hp + gap_v
    y1 = top2 + row_gap + pad["b"]
    ya, yb = y1 + max(0, hb - ha) / 2, y1 + max(0, ha - hb) / 2
    xb = x0 + a_width + gap_ab
    xz = xb + ar_r * hp + gap_rz
    row1 = [(a_stem, x0, round(ya, 1), round(a_width, 1), "a"),
            ("wt", round(xb, 1), round(yb + hp + gap_v, 1), round(ar_r * hp, 1), "b"),
            ("wt_helix_zoom", round(xz, 1), round(yb + hp + gap_v, 1), round(ar_z * hp, 1), None),
            ("mutant", round(xb, 1), round(yb, 1), round(ar_r * hp, 1), None),
            ("mutant_helix_zoom", round(xz, 1), round(yb, 1), round(ar_z * hp, 1), None)]
    height = y1 + max(ha, hb) + pad["t"] + 6 + 14
    return {**spec, "size": (spec["size"][0], round(height, 1)), "panels": row1 + below}


