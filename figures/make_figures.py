def find_panel(stem):
    """panels/ (generated) then source/ (hand-made) then si_panels/ (exported)."""
    for d in SEARCH:
        for ext in (".pdf", ".png", ".jpg", ".jpeg", ".tif", ".tiff", ".svg"):
            p = d / f"{stem}{ext}"
            if p.exists():
                return p
    return None


def _aspect(stem, default=1.4):
    """width/height of a panel, measured from the file. Default if absent.

    Measured rather than assumed because the supplementary grids mix panels
    whose aspect ratios run from 0.97 to 3.6; a single assumed ratio would
    overlap rows in some grids and leave gaps in others. A missing panel falls
    back to `default` so a layout still builds (with a placeholder box).
    """
    p = find_panel(stem)
    if p is None:
        return default
    try:
        if p.suffix.lower() == ".pdf":
            from pypdf import PdfReader
            box = PdfReader(str(p)).pages[0].mediabox
            return float(box.width) / float(box.height)
        from PIL import Image
        with Image.open(p) as im:
            return im.size[0] / im.size[1]
    except Exception:
        return default


def _size(stem, default=(368.4, 296.4)):
    """(width, height) of a panel in points, measured from the file.

    Same measurement as _aspect, kept separate because scaled_row needs the
    absolute native width and not just the ratio.

    RASTER PANELS ARE CONVERTED THROUGH THEIR DPI, which matters as soon as a
    row mixes raster with vector: the pipeline PNGs are 300 dpi, so a 2400 px
    panel is 576 pt of paper and not 2400. Returning pixels made scaled_row
    hand that panel four times the width of a vector neighbour and squeeze the
    rest of the row to nothing. A PNG with no dpi tag falls back to 72 dpi
    (pixels = points), which is the old behaviour.
    """
    p = find_panel(stem)
    if p is None:
        return default
    try:
        if p.suffix.lower() == ".pdf":
            from pypdf import PdfReader
            box = PdfReader(str(p)).pages[0].mediabox
            return float(box.width), float(box.height)
        from PIL import Image
        with Image.open(p) as im:
            w, h = im.size
            dx, dy = im.info.get("dpi", (72.0, 72.0))
        return float(w) * 72.0 / float(dx or 72.0), float(h) * 72.0 / float(dy or 72.0)
    except Exception:
        return default


def scaled_row(stems, y, letters, page_w=None, x0=10, gap=10):
    """One row placed at a COMMON SCALE rather than a common width.

    Equal widths would print the same kind of content at different
    magnifications: these panels are 325-383 pt wide natively, so a shared
    column width puts the ROC panel's text 13% larger than the sweep panels'.
    Equalising the scale factor instead makes text one size across the row,
    and -- because article_figures.py writes them all at the same native
    height -- lines their axes up on one baseline for free.

    Panels are bottom-aligned on `y`. Returns panel tuples for LAYOUTS.
    """
    page_w = page_w or WIDE
    nat = [_size(t) for t in stems]
    avail = page_w - 2 * x0 - (len(stems) - 1) * gap
    k = avail / sum(w for w, _ in nat)
    out, x = [], x0
    for stem, (w, _), letter in zip(stems, nat, letters):
        out.append((stem, round(x, 1), y, round(w * k, 1), letter))
        x += w * k + gap
    return out


def _top(panel):
    """Top edge of a placed panel, in points. Panels are (stem, x, y, w, letter)."""
    return panel[2] + panel[3] / _aspect(panel[0])


def suppress_baked_letters(panels, suffix="_combo"):
    """Blank the overlay letter for panels that already carry one.

    build() draws one letter per placed file, so a panel with its own letter
    baked into the PDF would print two. The combo ROC and N-sweep panels have
    theirs at 13 pt native; everything else relies on the overlay.
    """
    return [(st, x, y, w, None if st.endswith(suffix) else L)
            for st, x, y, w, L in panels]


def with_mirrored_pair(spec, left, right):
    """Swap two side-by-side panels, keeping the block's edges and its gap.

    Used to put the mutant helix zoom on the INSIDE of its pair, so the two
    ensembles in row b mirror each other about the page centre instead of both
    running wide-then-narrow.
    """
    at = {t[0]: t for t in spec["panels"]}
    lx, lw = at[left][1], at[left][3]
    rx, rw = at[right][1], at[right][3]
    gap = rx - (lx + lw)
    moved = {left: lx + rw + gap, right: lx}
    return {**spec,
            "panels": [(st, moved.get(st, x), y, w, L)
                       for st, x, y, w, L in spec["panels"]]}


def with_taller_panel(spec, stem, new_stem):
    """Swap one panel's file and push everything above it up by its height change.

    A panel's height is its placed width over the file's own bbox aspect, so
    re-rendering it taller silently grows it INTO the row above. This lifts
    every panel that sat above the old top by exactly the change, and grows the
    page by the same amount, so the gap above it is preserved rather than eaten.
    """
    old = next(t for t in spec["panels"] if t[0] == stem)
    dy = round(old[3] / _aspect(new_stem) - old[3] / _aspect(stem), 1)
    top = _top(old)
    panels = [(new_stem, x, y, w, L) if st == stem
              else (st, x, y + dy, w, L) if y >= top - 1e-6
              else (st, x, y, w, L)
              for st, x, y, w, L in spec["panels"]]
    return {**spec, "size": (spec["size"][0], spec["size"][1] + dy),
            "panels": panels}


def with_row4(spec, row4, caption):
    """A copy of a figure with a different bottom row, everything above shifted.

    Exists so Figure1_KS is DERIVED from Figure 1 rather than a second copy of
    its layout. Figure 1 has been re-stacked five times in a day; two hand-kept
    copies of an eleven-panel stack would have diverged by the next edit.

    The shift is not cosmetic bookkeeping. Row 4's height comes from the panels
    in it -- swapping a 360 pt-tall sweep raster for the 296.4 pt vector version
    lifts that row's top by 23 pt, and everything above it has to move by the
    same amount or a panel letter prints on the panel above.
    """
    old4 = [t for t in spec["panels"] if t[2] == spec["panels"][-1][2]
            and (t[4] in ("f", "g", "h") or t[4] is None)]
    new4 = suppress_baked_letters(matched_row(row4, y=old4[0][2], letters="fgh"))
    dy = round(_top(new4[0]) - _top(old4[0]))
    above = [(st, x, y + dy, w, L) for st, x, y, w, L in spec["panels"]
             if (st, x, y, w, L) not in old4]
    return {**spec, "size": (spec["size"][0], spec["size"][1] + dy),
            "caption": caption, "panels": above + new4}


def matched_row(stems, y, letters, page_w=None, x0=10, gap=10):
    """One row placed at a COMMON HEIGHT, filling the width.

    The alternative to scaled_row, and the trade is explicit: equal heights
    line the panels up top and bottom, which is what a row of three plots
    should look like, but they can only be equal if the panels are scaled
    unequally. Here f and g are 296.4 pt tall natively and h is 360, so
    matching heights puts h at scale 0.50 against their 0.61 -- its text is
    about a fifth smaller than theirs. Use scaled_row when one text size across
    the row matters more, this when the alignment does.

    Panels sit on `y`; every one has the same height by construction.
    """
    page_w = page_w or WIDE
    nat = [_size(t) for t in stems]
    avail = page_w - 2 * x0 - (len(stems) - 1) * gap
    h = avail / sum(w / hh for w, hh in nat)      # common height, widths fill
    out, x = [], x0
    for stem, (w, hh), letter in zip(stems, nat, letters):
        out.append((stem, round(x, 1), y, round(h * w / hh, 1), letter))
        x += h * w / hh + gap
    return out


def grid(stems, cols, page_w=None, x0=10, gap=12, y0=14, row_gap=30,
         letters=True, start=0):
    """Lay panels out left-to-right, bottom-to-top. Returns (panels, height).

    Rows are built top-down for reading order but POSITIONED bottom-up, because
    PDF y grows upward: the last row has to be placed first to know where the
    one above it begins. Each panel is bottom-aligned within its row, and a
    row's height is that of its tallest member.

    Panel letters follow reading order, so they are assigned from the row index
    rather than from the placement order.
    """
    page_w = page_w or WIDE
    w = (page_w - 2 * x0 - (cols - 1) * gap) / cols
    rows = [stems[i:i + cols] for i in range(0, len(stems), cols)]
    heights = [max(w / _aspect(t) for t in row) for row in rows]
    offsets = []                      # index of each row's first panel
    n = 0
    for row in rows:
        offsets.append(n)
        n += len(row)

    panels, y = [], y0
    for r in range(len(rows) - 1, -1, -1):      # bottom row of the page first
        for k, stem in enumerate(rows[r]):
            ph = w / _aspect(stem)
            i = start + offsets[r] + k
            panels.append((stem, x0 + k * (w + gap), y + (heights[r] - ph), w,
                           chr(ord("a") + i) if letters else None))
        y += heights[r] + row_gap
    panels.sort(key=lambda t: (-t[2], t[1]))    # reading order in the build log
    return panels, y - row_gap + 26


def si_rows(rows, caption, page_w=None, x0=10, gap=14, row_gap=10, letter_room=18,
            placeholder=(436, 250)):
    """A supplementary figure as rows of panels at NATIVE scale. Returns a spec.

    The v6 SI panels are written by figures/si/lib at their final journal
    width (89 or 180 mm) with their final text size, so they are placed 1:1 and
    left-aligned; only a row wider than the page is shrunk, and then the whole
    figure shrinks with it so the text stays one size. Rows run top to bottom,
    letters in reading order. A missing panel is sized `placeholder` (w, h) so the
    figure still builds with a dashed box (build() draws it).
    """
    page_w = page_w or COL2
    nat = [[_size(t, placeholder) for t in row] for row in rows]
    widest = max(sum(w for w, _ in r) + gap * (len(r) - 1) for r in nat)
    k = min(1.0, (page_w - 2 * x0) / widest)
    heights = []
    for row, r in zip(rows, nat):
        # build() draws a missing panel 0.75 x its width tall
        hs = [h * k if find_panel(t) else 0.75 * w * k for t, (w, h) in zip(row, r)]
        heights.append(max(hs))
    total = sum(heights) + len(rows) * letter_room + (len(rows) - 1) * row_gap + 8
    panels, y, n = [], total, 0
    for row, r, hgt in zip(rows, nat, heights):
        y -= letter_room + hgt
        x = x0
        for stem, (w, _) in zip(row, r):
            panels.append((stem, round(x, 1), round(y, 1), round(w * k, 1), chr(ord("a") + n)))
            x += w * k + gap
            n += 1
        y -= row_gap
    return {"size": (page_w, round(total, 1)), "caption": caption, "panels": panels}


